-- Countify AI Creator 4.0
-- Apply after the existing platform/billing migrations.

create table if not exists public.ai_conversations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade,
  title text not null default 'Countify AI session',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ai_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.ai_conversations(id) on delete cascade,
  user_id uuid references auth.users(id) on delete cascade,
  role text not null check (role in ('user','assistant','system')),
  content text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.ai_memory (
  user_id uuid primary key references auth.users(id) on delete cascade,
  preferred_style text not null default '',
  language text not null default '',
  tone text not null default '',
  timezone text not null default '',
  notes text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.ai_usage_daily (
  quota_key text not null,
  usage_date date not null default current_date,
  request_count integer not null default 0,
  updated_at timestamptz not null default now(),
  primary key (quota_key, usage_date)
);

alter table public.ai_conversations enable row level security;
alter table public.ai_messages enable row level security;
alter table public.ai_memory enable row level security;
alter table public.ai_usage_daily enable row level security;

create policy "users manage own ai conversations" on public.ai_conversations
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users manage own ai messages" on public.ai_messages
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users manage own ai memory" on public.ai_memory
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

create index if not exists ai_conversations_user_idx on public.ai_conversations(user_id, updated_at desc);
create index if not exists ai_messages_conversation_idx on public.ai_messages(conversation_id, created_at);
create index if not exists ai_usage_daily_date_idx on public.ai_usage_daily(usage_date, updated_at desc);

create or replace function public.consume_ai_quota(p_key text, p_limit integer default 25)
returns table(allowed boolean, remaining integer)
language plpgsql
security definer
set search_path = public
as $$
declare current_count integer;
begin
  insert into public.ai_usage_daily(quota_key, usage_date, request_count)
  values (p_key, current_date, 1)
  on conflict (quota_key, usage_date)
  do update set request_count = ai_usage_daily.request_count + 1, updated_at = now()
  returning request_count into current_count;

  if current_count > p_limit then
    update public.ai_usage_daily
      set request_count = current_count - 1, updated_at = now()
      where quota_key = p_key and usage_date = current_date;
    return query select false, 0;
  end if;

  return query select true, greatest(p_limit - current_count, 0);
end;
$$;

grant execute on function public.consume_ai_quota(text, integer) to anon, authenticated, service_role;
