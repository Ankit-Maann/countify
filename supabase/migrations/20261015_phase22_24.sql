-- Phase 22–24 optional Cloud schema.
-- Run this only when Supabase Cloud is enabled. RLS keeps creator data private by default.
create table if not exists public.creator_profiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  username text not null unique,
  display_name text not null default 'Countdown Creator',
  bio text not null default '',
  avatar text not null default '✨',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.creator_follows (
  follower_id uuid not null references auth.users(id) on delete cascade,
  creator_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (follower_id, creator_id),
  check (follower_id <> creator_id)
);

create table if not exists public.countdown_bookmarks (
  user_id uuid not null references auth.users(id) on delete cascade,
  countdown_id uuid not null references public.countdowns(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, countdown_id)
);

create table if not exists public.countdown_likes (
  user_id uuid not null references auth.users(id) on delete cascade,
  countdown_id uuid not null references public.countdowns(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, countdown_id)
);

create table if not exists public.countdown_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid references auth.users(id) on delete set null,
  countdown_id uuid references public.countdowns(id) on delete cascade,
  reason text not null,
  status text not null default 'open' check (status in ('open','reviewing','resolved','dismissed')),
  created_at timestamptz not null default now()
);

alter table public.creator_profiles enable row level security;
alter table public.creator_follows enable row level security;
alter table public.countdown_bookmarks enable row level security;
alter table public.countdown_likes enable row level security;
alter table public.countdown_reports enable row level security;

create policy "profiles are public to read" on public.creator_profiles for select using (true);
create policy "owners manage profile" on public.creator_profiles for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users manage own follows" on public.creator_follows for all using (auth.uid() = follower_id) with check (auth.uid() = follower_id);
create policy "users manage own bookmarks" on public.countdown_bookmarks for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users manage own likes" on public.countdown_likes for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users submit reports" on public.countdown_reports for insert with check (auth.uid() = reporter_id);

create index if not exists creator_profiles_username_idx on public.creator_profiles(username);
create index if not exists countdown_bookmarks_user_idx on public.countdown_bookmarks(user_id, created_at desc);
create index if not exists countdown_likes_countdown_idx on public.countdown_likes(countdown_id);
create index if not exists countdown_reports_status_idx on public.countdown_reports(status, created_at desc);
