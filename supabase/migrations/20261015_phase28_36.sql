-- Countify Phases 28–36 production schema.
-- Apply after the Phase 22–24 migration. Billing provider secrets/webhooks MUST remain server-side.

create table if not exists public.subscriptions (
  id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id) on delete cascade,
  provider text not null, provider_customer_id text, provider_subscription_id text unique,
  plan text not null check (plan in ('pro_monthly','pro_yearly','business')),
  status text not null default 'pending' check (status in ('pending','trialing','active','past_due','canceled','expired')),
  current_period_end timestamptz, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.creator_themes (
  id uuid primary key default gen_random_uuid(), creator_id uuid not null references auth.users(id) on delete cascade,
  name text not null, slug text not null unique, description text not null default '', design jsonb not null default '{}'::jsonb,
  price_minor integer not null default 0 check (price_minor >= 0), currency text not null default 'INR',
  is_published boolean not null default false, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.theme_purchases (
  id uuid primary key default gen_random_uuid(), buyer_id uuid not null references auth.users(id) on delete cascade,
  theme_id uuid not null references public.creator_themes(id) on delete cascade, provider_payment_id text,
  created_at timestamptz not null default now(), unique (buyer_id, theme_id)
);

create table if not exists public.workspaces (
  id uuid primary key default gen_random_uuid(), owner_id uuid not null references auth.users(id) on delete cascade,
  name text not null, slug text not null unique, brand jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create table if not exists public.workspace_members (
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('owner','admin','editor','viewer')),
  created_at timestamptz not null default now(), primary key (workspace_id,user_id)
);
create table if not exists public.embed_events (
  id bigint generated by default as identity primary key, countdown_id uuid references public.countdowns(id) on delete cascade,
  visitor_id text, referrer text, created_at timestamptz not null default now()
);
create table if not exists public.creator_earnings (
  id uuid primary key default gen_random_uuid(), creator_id uuid not null references auth.users(id) on delete cascade,
  source text not null, gross_minor integer not null default 0, platform_fee_minor integer not null default 0,
  net_minor integer not null default 0, currency text not null default 'INR', status text not null default 'pending',
  provider_reference text, created_at timestamptz not null default now()
);

