alter table public.creator_earnings enable row level security;

create policy "users read own subscriptions" on public.subscriptions for select using (auth.uid() = user_id);
create policy "published themes are public" on public.creator_themes for select using (is_published = true or auth.uid() = creator_id);
create policy "creators manage themes" on public.creator_themes for all using (auth.uid() = creator_id) with check (auth.uid() = creator_id);
create policy "buyers read own purchases" on public.theme_purchases for select using (auth.uid() = buyer_id);
create policy "workspace owners manage" on public.workspaces for all using (auth.uid() = owner_id) with check (auth.uid() = owner_id);
create policy "members read membership" on public.workspace_members for select using (auth.uid() = user_id);
create policy "members manage own membership" on public.workspace_members for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "embed events are insert only" on public.embed_events for insert with check (true);
create policy "creators read own earnings" on public.creator_earnings for select using (auth.uid() = creator_id);

create index if not exists subscriptions_user_status_idx on public.subscriptions(user_id,status,current_period_end desc);
create index if not exists creator_themes_creator_idx on public.creator_themes(creator_id,created_at desc);
