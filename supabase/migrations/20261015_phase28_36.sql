create index if not exists workspace_members_user_idx on public.workspace_members(user_id,created_at desc);
create index if not exists embed_events_countdown_idx on public.embed_events(countdown_id,created_at desc);
create index if not exists creator_earnings_creator_idx on public.creator_earnings(creator_id,created_at desc);

-- Phase 31 billing entitlement helpers.
create or replace function public.get_my_subscription()
returns table (
  active boolean,
  plan text,
  status text,
  current_period_end timestamptz,
  provider text
)
language sql
security definer
set search_path = public
as $$
  select
    (
      s.status in ('active', 'trialing')
      and (s.current_period_end is null or s.current_period_end > now())
    ) as active,
    s.plan,
    s.status,
    s.current_period_end,
    s.provider
  from public.subscriptions s
  where s.user_id = auth.uid()
  order by
    case when s.status in ('active', 'trialing') then 0 else 1 end,
    s.current_period_end desc nulls last,
    s.updated_at desc
  limit 1;
$$;

grant execute on function public.get_my_subscription() to authenticated;

create index if not exists subscriptions_customer_idx
  on public.subscriptions(provider, provider_customer_id);

